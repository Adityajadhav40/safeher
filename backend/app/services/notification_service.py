def build_location_url(
    latitude: float,
    longitude: float,
) -> str:
    return (
        "https://www.google.com/maps/search/"
        f"?api=1&query={latitude},{longitude}"
    )


def build_sms_message(
    user_name: str,
    district: str | None,
    risk_level: str | None,
    risk_score: float | None,
    latitude: float,
    longitude: float,
) -> str:

    risk_text = (
        f"{risk_level} ({risk_score:.1f}/100)"
        if risk_level is not None
        and risk_score is not None
        else "UNKNOWN"
    )

    district_text = district or "Unknown"

    location_url = build_location_url(
        latitude=latitude,
        longitude=longitude,
    )

    return (
        "🚨 SAFEHER SOS ALERT\n"
        f"{user_name} has activated an emergency SOS.\n"
        f"Location: {district_text}\n"
        f"Risk: {risk_text}\n"
        f"GPS: {latitude:.6f}, {longitude:.6f}\n"
        f"Location: {location_url}"
    )


