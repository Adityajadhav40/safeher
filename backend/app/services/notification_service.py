def get_user_emergency_contacts(
    db: Session,
    user_id: str,
) -> list[EmergencyContact]:

    statement = (
        select(EmergencyContact)
        .where(
            EmergencyContact.user_id == user_id
        )
        .order_by(
            EmergencyContact.created_at.asc()
        )
    )

    return list(
        db.execute(statement)
        .scalars()
        .all()
    )


# ============================================================
# CREATE NOTIFICATION RECORD
# ============================================================

def create_notification_record(
    db: Session,
    sos_id: str,
    user_id: str,
    channel: str,
    recipient: str,
) -> Notification:

    channel = channel.strip().upper()

    allowed_channels = {
        "SMS",
        "EMAIL",
    }

    if channel not in allowed_channels:
        raise ValueError(
            "Unsupported notification channel."
        )

    notification = Notification(
        sos_id=sos_id,
        user_id=user_id,
        channel=channel,
        recipient=recipient,
        status="PENDING",
    )

    db.add(notification)

    try:
        db.commit()
        db.refresh(notification)

    except Exception:
        db.rollback()
        raise

    return notification


# ============================================================
# MARK NOTIFICATION SENT
# ============================================================

def mark_notification_sent(
    db: Session,
    notification_id: str,
    provider: str | None = None,
    provider_message_id: str | None = None,
) -> Notification | None:

    statement = (
        select(Notification)
        .where(
            Notification.id ==
            notification_id
        )
    )

    notification = (
        db.execute(statement)
        .scalar_one_or_none()
    )

    if notification is None:
        return None

    notification.status = "SENT"

    notification.provider = provider

    notification.provider_message_id = (
        provider_message_id
    )

    notification.error_message = None

    notification.sent_at = (
        datetime.now(timezone.utc)
    )

    notification.updated_at = (
        datetime.now(timezone.utc)
    )

    try:
        db.commit()
        db.refresh(notification)

    except Exception:
        db.rollback()
        raise

    return notification


# ============================================================
# MARK NOTIFICATION FAILED
# ============================================================

def mark_notification_failed(
    db: Session,
    notification_id: str,
    error_message: str,
    provider: str | None = None,
) -> Notification | None:

    statement = (
        select(Notification)
        .where(
            Notification.id ==
            notification_id
        )
    )

    notification = (
        db.execute(statement)
        .scalar_one_or_none()
    )

    if notification is None:
        return None

    notification.status = "FAILED"

    notification.provider = provider

    notification.error_message = (
        error_message[:2000]
        if error_message
        else "Notification delivery failed."
    )

    notification.updated_at = (
        datetime.now(timezone.utc)
    )

    try:
        db.commit()
        db.refresh(notification)

    except Exception:
        db.rollback()
        raise

    return notification


# ============================================================
# GET SOS NOTIFICATIONS
# ============================================================

def get_sos_notifications(
    db: Session,
    user_id: str,
    sos_id: str,
) -> list[Notification]:

    statement = (
        select(Notification)
        .where(
            Notification.sos_id == sos_id,
            Notification.user_id == user_id,
        )
        .order_by(
            Notification.created_at.asc()
        )
    )

    return list(
        db.execute(statement)
        .scalars()
        .all()
    )